def create_probability_fixture(directory: Path) -> dict:
    """One 3x2 view with known zero, unknown, background and valid samples."""
    quantization = 65534
    values = (0, quantization // 4, 65535, 65535, 65535, quantization)
    states = bytes((3, 3, 2, 0, 1, 3))
    blob = struct.pack('<6H', *values) + states + bytes(6)
    compressed = gzip.compress(blob, mtime=0)
    digest = hashlib.sha256(blob).hexdigest()
    relative = f'shards/synthetic_usa_0/fixture/{digest}.bin'
    target = directory / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(blob)
    target.with_suffix('.bin.gz').write_bytes(compressed)
    entry = {
        'id': 'synthetic-entry', 'target_id': 'synthetic_usa_0',
        'configuration_id': 'synthetic_usa_0', 'ammo_id': 'SYNTHETIC ROUND',
        'ammo_profile_sha256': hashlib.sha256(b'synthetic-ammo').hexdigest(),
        'physical_distance_m': 1000, 'geometry_version': 'synthetic-geometry',
        'configuration_version': 'synthetic-materials', 'model_version': 'synthetic-physics',
        'source_version': 'synthetic-test-only', 'mode': 'KE',
        'width': 3, 'height': 2, 'pixel_pitch_m': 0.1, 'angles_deg': [0],
        'world_width_m': 0.3, 'top_y_m': 0.2, 'bottom_y_m': 0,
        'conditions': 'Synthetic test fixture, not game data',
        'coordinate_convention': 'row-major synthetic test pixels',
        'reference_only': True,
        'shards': [{'angle_index': 0, 'angle_deg': 0, 'url': relative,
                    'gzip_url': relative + '.gz', 'sha256': digest,
                    'gzip_sha256': hashlib.sha256(compressed).hexdigest(),
                    'bytes': len(blob), 'gzip_bytes': len(compressed)}],
    }
    index = {
        'schema_version': 1, 'kind': 'conditional-probability-atlas',
        'source_version': 'synthetic-test-only', 'entries': [entry],
        'reference_ammunition_is_not_availability': True,
        'encoding': {'probability_dtype': 'uint16-le', 'quantization_max': quantization,
                     'unknown_value': 65535, 'layout': ['probability', 'status', 'material_response_flags'],
                     'order': 'row-major image_y,image_x', 'status_dtype': 'uint8', 'flags_dtype': 'uint8'},
        'status_legend': {'0': 'background', '1': 'no protected target', '2': 'unknown', '3': 'valid'},
        'flag_legend': {}, 'scope': {'test_fixture': True},
    }
    index['content_hash'] = hashlib.sha256(json.dumps(index, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    write_json(directory / 'index.json', index)
    (directory / 'index.json.gz').write_bytes(gzip.compress((directory / 'index.json').read_bytes(), mtime=0))
    write_json(directory / 'export-report.json', {'test_fixture': True, 'targets': 1, 'views': 1})
    return index


def create_fixture(root: Path) -> Path:
    root = root.resolve()
    root.mkdir(parents=True, exist_ok=True)
    if any(root.iterdir()):
        raise ValueError('Synthetic fixtures require an empty output directory.')
    shutil.copytree(PROJECT / 'config', root / 'config')
    shutil.copytree(PROJECT / 'web', root / 'web', ignore=shutil.ignore_patterns('data', 'shared', '__pycache__'))
    shutil.copytree(PROJECT / 'shared', root / 'shared')
    write_json(root / 'config/hosting.json', {
        'schema_version': '1.0.0', 'bind': '127.0.0.1', 'port': 8080,
        'public_directory': 'dist/site', 'cache_seconds': 31536000, 'open_browser': False,
    })
    write_json(root / 'config/deployment.json', {
        'schema_version': '1.0.0',
        'probability': {'mode': 'disabled', 'base_url': ''},
        'budgets': {'site_bytes': 104857600, 'file_bytes': 26214400},
    })
    catalog = {
        'schema_version': '1.0.0',
        'snapshot': {'id': 'synthetic-ci-only', 'status': 'test_fixture', 'game_version': None},
        'nations': [{'id': 'usa', 'label': 'Fixture USA'}, {'id': 'ussr', 'label': 'Fixture USSR'}],
        'vehicles': [_vehicle(nation, number) for nation in ('usa', 'ussr') for number in range(3)],
    }
    write_json(root / 'data/snapshots/catalog.json', catalog)
    write_json(root / 'data/snapshots/changes.json', {
        'schema_version': '1.0.0', 'status': 'test_fixture',
        'entries': [{'vehicle_id': 'synthetic_usa_0', 'field': 'br', 'old': 10.0, 'new': 10.3}],
    })
    write_json(root / 'data/snapshots/decision-probabilities.json', {
        'schema_version': '1.0.0', 'status': 'test_fixture', 'records': [],
    })
    write_json(root / 'data/snapshots/target-layers.json', {
        'schema_version': '1.0.0', 'status': 'test_fixture', 'targets': [],
    })
    write_json(root / 'reports/target-layers.json', {'status': 'test_fixture', 'targets': 0, 'sampled_rays': 0})
    create_probability_fixture(root / 'data/exports/probability')
    build_recommendations(root)
    return root


def build_recommendations(root: Path) -> None:
    """Run the actual recommendation builder after a fixture input changes."""
    node = os.environ.get('GROUNDOPS_NODE') or shutil.which('node')
    if not node:
        raise RuntimeError('Node.js is required for the real synthetic recommendation build.')
    command = [node, str(PROJECT / 'scripts/build_decisions.mjs'),
               '--catalog', str(root / 'data/snapshots/catalog.json'),
               '--scenario', str(root / 'data/snapshots/changes.json'),
               '--config', str(root / 'config/model.json'),
               '--probabilities', str(root / 'data/snapshots/decision-probabilities.json'),
               '--target-layers', str(root / 'data/snapshots/target-layers.json'),
               '--out', str(root / 'data/derived/recommendations')]
    subprocess.run(command, cwd=PROJECT, check=True, capture_output=True, text=True)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--build', action='store_true')
    parser.add_argument('--probability-mode', choices=('disabled', 'external', 'embedded'), default='disabled')
    parser.add_argument('--probability-base-url')
    options = parser.parse_args()
    project = create_fixture(options.output)
    if options.build:
        load_script('build_web').build(project, probability_mode=options.probability_mode,
                                       probability_base_url=options.probability_base_url)
    print(json.dumps({'fixture': str(project), 'synthetic_test_data_only': True}))
